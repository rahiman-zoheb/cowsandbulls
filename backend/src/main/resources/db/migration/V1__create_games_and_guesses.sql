-- Hibernate validates the entities against this schema at startup
-- (spring.jpa.hibernate.ddl-auto=validate), so a mapping that drifts from it
-- fails fast instead of silently altering tables.

create table game (
    id               uuid                     not null,
    secret           varchar(4)               not null,
    status           varchar(16)              not null,
    created_at       timestamp(6) with time zone not null,
    last_activity_at timestamp(6) with time zone not null,
    version          bigint,
    constraint pk_game primary key (id),
    constraint ck_game_status check (status in ('IN_PROGRESS', 'WON', 'LOST'))
);

-- GameCleanup deletes by last_activity_at.
create index ix_game_last_activity_at on game (last_activity_at);

create table guess (
    id      bigint generated by default as identity,
    game_id uuid       not null,
    name    varchar(4) not null,
    cows    integer    not null,
    bulls   integer    not null,
    constraint pk_guess primary key (id),
    -- Expiry deletes games with one bulk statement, so guesses must go with
    -- them at the database level.
    constraint fk_guess_game foreign key (game_id) references game (id) on delete cascade
);

create index ix_guess_game_id on guess (game_id);
